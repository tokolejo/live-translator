  parseGlossary(raw) {
    this.geoToEngRules = [];
    this.engToGeoRules = [];
    const lines = raw.split('\n');
    let totalPairs = 0;

    lines.forEach(line => {
      const idx = line.indexOf(':');
      if (idx !== -1) {
        const left = line.slice(0, idx).trim();
        const right = line.slice(idx + 1).trim();
        if (left && right) {
          totalPairs++;
          const leftEsc = left.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
          const rightEsc = right.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

          // Left is Geo, Right is Eng (or vice-versa)
          const leftIsGeo = /[\u10A0-\u10FF]/.test(left);
          if (leftIsGeo) {
            this.geoToEngRules.push({
              regex: new RegExp(leftEsc, 'gi'),
              to: right,
              len: left.length
            });
            this.engToGeoRules.push({
              regex: new RegExp(rightEsc, 'gi'),
              to: left,
              len: right.length
            });
          } else {
            this.engToGeoRules.push({
              regex: new RegExp(leftEsc, 'gi'),
              to: right,
              len: left.length
            });
            this.geoToEngRules.push({
              regex: new RegExp(rightEsc, 'gi'),
              to: left,
              len: right.length
            });
          }
        }
      }
    });

    // Sort longer matches first for maximum greedy accuracy
    this.geoToEngRules.sort((a, b) => b.len - a.len);
    this.engToGeoRules.sort((a, b) => b.len - a.len);

    if (this.glossaryCount) {
      this.glossaryCount.textContent = totalPairs;
    }
  }

  applyGlossary(text, targetLang = null) {
    if (!text) return '';
    let result = text;
    const tgt = targetLang || this.currentTgtLang;

    // If translating into English, apply Geo -> Eng rules
    // If translating into Georgian, apply Eng -> Geo rules
    const rules = (tgt === 'en') ? this.geoToEngRules : this.engToGeoRules;

    if (rules && rules.length > 0) {
      for (let i = 0; i < rules.length; i++) {
        const rule = rules[i];
        if (rule.regex.test(result)) {
          result = result.replace(rule.regex, rule.to);
        }
      }
    }
    return result;
  }

